export function useI18n() {
  const session = useSession();
  const language = normalizeLanguage(session.user?.preferredLanguage);
  return useMemo(() => {
    const info = languageInfo(language);
    const t = (key: string) => TEXT[language]?.[key] ?? TEXT.en[key] ?? key;
    return { language, info, t };
  }, [language]);
}

export function translateUi(languageValue: string | null | undefined, key: string) {
  const language = normalizeLanguage(languageValue);
  return TEXT[language]?.[key] ?? TEXT.en[key] ?? key;
}
